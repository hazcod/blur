// FuzzMultiAgentTextRecall mutates a small real encrypted history at runtime.
// Its oracle is the independent insertion/deletion/scope ledger, never a
// generated answer, retrieved passage, or the production subject recognizer.
func FuzzMultiAgentTextRecall(f *testing.F) {
	for _, seed := range [][]byte{
		{},
		{8, 0, 1, 9, 1, 0, 7, 0, 1, 5, 1, 2, 0, 2, 5},
		{4, 1, 1, 3, 1, 1, 4, 3, 2, 4, 2, 1, 3, 0, 1},
		{2, 0, 0, 1, 0, 1, 1, 1, 4, 3, 5, 2, 2, 4, 0},
		{7, 1, 1, 5, 0, 0, 3, 2, 5, 0, 1, 4, 3, 2, 5},
		{8, 1, 0, 4, 1, 1, 8, 3, 5, 1, 5, 3, 2, 4, 1},
	} {
		f.Add(seed)
	}
	// One boundary seed puts all ten short factual lines at 8KiB tails. The
	// generated byte stream is decoded by the same runtime path as mutations.
	tailSeed := []byte{8, 0, 1, 9, 1, 0, 3}
	for i := 0; i < 10; i++ {
		tailSeed = append(tailSeed, byte(i%4), byte(i), byte(i%6), byte(i), 0, byte(i), 5, 1)
	}
	f.Add(tailSeed)
	f.Fuzz(func(t *testing.T, input []byte) {
		t.Setenv("TZ", "UTC")
		if len(input) > 128 {
			input = input[:128]
		}
		parameters := multiAgentJourneyInput{data: input}
		count := 2 + int(parameters.next()%9)
		apps := [...]struct{ id, name string }{{"com.apple.terminal", "Terminal"}, {"com.tinyspeck.slackmacgap", "Slack"}}
		appIndex := int(parameters.next() % 2)
		app := apps[appIndex]
		scoped := parameters.next()&1 != 0
		unavailable := int(parameters.next()) % count
		deleteAtBoundary := parameters.next()&1 != 0
		reopenBeforeDelete := parameters.next()&1 != 0
		rotation := int(parameters.next()) % count
		now := time.Date(2026, 11, 22, 12, 0, 0, 0, time.UTC)
		ctx := context.Background()
		path, key := filepath.Join(t.TempDir(), "text-agents.db"), securestore.OfflineFixtureKey()
		var store *durable.Store
		var client *Client
		open := func(mode durable.OpenMode) {
			t.Helper()
			var err error
			store, err = durable.OpenDurable(path, key, mode)
			if err != nil {
				t.Fatal(err)
			}
			client = NewClient(store)
			client.askNow = func() time.Time { return now }
		}
		closeStore := func() {
			t.Helper()
			client.Close()
			if err := store.Close(); err != nil {
				t.Fatal(err)
			}
		}
		open(durable.CreateNew)
		t.Cleanup(func() { client.Close(); _ = store.Close() })
		type original struct {
			subject, id, app, fact string
			at                     time.Time
			live, current          bool
		}
		originals := make([]original, count)
		labels := make([]string, count)
		var rejectedFacts []string
		records := 0
		put := func(appID, body string, at time.Time) string {
			t.Helper()
			if len(body) > 8<<10 {
				t.Fatal("fixture exceeded its per-source work bound")
			}
			o, err := capture.SanitizeObservation(appID, "agent-logs.example", body, 8<<10)
			if err != nil {
				t.Fatal(err)
			}
			if o.Text() != body || o.Truncated() {
				t.Fatal("fixture did not preserve independently authored terminal text")
			}
			if err := store.PutObservationAt(ctx, o, at); err != nil {
				t.Fatal(err)
			}
			records++
			if records > 20 {
				t.Fatal("fixture grew beyond twenty observations")
			}
			return o.ContentID()
		}
		stems := [...]string{"agent", "review", "worker", "audit"}
		tasks := [...]string{"parser calibration", "index validation", "queue cleanup", "schema checks", "search checkpoint", "cache inspection"}
		for i := range originals {
			label := fmt.Sprintf("%s_%02x%02d", stems[int(parameters.next())%len(stems)], parameters.next(), i)
			labels[i] = label
			task := tasks[int(parameters.next())%len(tasks)]
			fact := fmt.Sprintf("%s finished %s stage %02x.", label, task, parameters.next())
			state := parameters.next() % 5
			appID := app.id
			at := now.Add(-time.Duration(2+int(parameters.next()%58)) * time.Minute)
			current := state != 3
			if !current {
				at = at.Add(-24 * time.Hour)
			}
			if state == 4 {
				appID = apps[1-appIndex].id
			}
			// Every execution has a live in-scope anchor plus a requested missing or
			// subsequently deleted subject; other subjects vary independently.
			if i == (unavailable+1)%count || i == unavailable && deleteAtBoundary {
				current = true
				appID = app.id
				at = now.Add(-time.Hour)
			}
			item := original{subject: label, app: appID, fact: fact, at: at, current: current}
			body := multiAgentTerminalBody(fact, parameters.next(), parameters.next())
			if i != unavailable || deleteAtBoundary {
				item.id = put(appID, body, at)
				item.live = true
			}
			originals[i] = item
		}
		// Strict prefix lookalikes are recent and in-app, so neither date nor app
		// filtering can accidentally make the identifier-boundary assertion pass.
		suffixes := [...]string{"_extra", "_v2", "-child", ".py", "/child"}
		for i, n := 0, 1+int(parameters.next()%4); i < n; i++ {
			label := labels[int(parameters.next())%count] + suffixes[int(parameters.next())%len(suffixes)]
			fact := fmt.Sprintf("%s finished unrelated decoy maintenance %d.", label, i)
			rejectedFacts = append(rejectedFacts, fact)
			put(app.id, multiAgentTerminalBody(fact, parameters.next(), parameters.next()), now.Add(-time.Minute))
		}
		requested := append(slices.Clone(labels[rotation:]), labels[:rotation]...)
		names := strings.Join(requested[:len(requested)-1], ", ") + " and " + requested[len(requested)-1]
		question := "What did " + names + " each finish"
		if scoped {
			question += " in " + app.name
		}
		question += " today?"
		check := func(stage string) {
			t.Helper()
			wanted := map[string]original{}
			var missing []string
			for _, item := range originals {
				if item.id != "" && item.live && item.current && (!scoped || item.app == app.id) {
					wanted[item.id] = item
				} else {
					missing = append(missing, item.subject)
				}
			}
			result, err := client.AskMemory(ctx, question)
			if err != nil {
				t.Fatalf("%s input=%x question=%q: %v", stage, input, question, err)
			}
			planSubjects := slices.Clone(result.Plan.TechnicalSubjects)
			slices.Sort(planSubjects)
			expectedSubjects := slices.Clone(labels)
			slices.Sort(expectedSubjects)
			if !slices.Equal(planSubjects, expectedSubjects) {
				t.Fatalf("%s input=%x changed requested agents: want=%v got=%v", stage, input, expectedSubjects, planSubjects)
			}
			seen := map[string]bool{}
			for _, source := range result.Sources {
				item, ok := wanted[source.SourceID]
				if !ok {
					t.Fatalf("%s input=%x cited a missing/deleted/out-of-scope/lookalike source %s", stage, input, source.SourceID)
				}
				if source.AppID != item.app || !source.CapturedAt.Equal(item.at) || !strings.Contains(source.Text, item.fact) {
					t.Fatalf("%s input=%x lost factual source provenance for %s", stage, input, item.subject)
				}
				if len(source.TechnicalSubjects) != 1 || source.TechnicalSubjects[0] != item.subject {
					t.Fatalf("%s input=%x assigned another agent to %s: %v", stage, input, item.subject, source.TechnicalSubjects)
				}
				seen[source.SourceID] = true
			}
			for _, id := range result.Answer.SourceIDs {
				if _, ok := wanted[id]; !ok {
					t.Fatalf("%s input=%x fabricated/retained forbidden citation %s", stage, input, id)
				}
			}
			for id, item := range wanted {
				if !seen[id] || !slices.Contains(result.Answer.SourceIDs, id) {
					t.Fatalf("%s input=%x omitted feasible agent %s: expected=%d sources=%d cited=%d limited=%t missing=%v", stage, input, item.subject, len(wanted), len(result.Sources), len(result.Answer.SourceIDs), result.CoverageLimited, missing)
				}
			}
			if result.Answer.InsufficientEvidence {
				t.Fatalf("%s input=%x rejected the guaranteed in-scope anchor", stage, input)
			}
			if len(missing) > 0 {
				paragraphs := strings.Split(result.Answer.Text, "\n\n")
				gap := paragraphs[len(paragraphs)-1]
				disclosed := strings.Contains(strings.ToLower(gap), "verify") || strings.Contains(strings.ToLower(gap), "missing") || strings.Contains(strings.ToLower(gap), "uncovered") || strings.Contains(strings.ToLower(gap), "insufficient")
				if !result.CoverageLimited || !disclosed {
					t.Fatalf("%s input=%x hid missing-agent coverage: missing=%v limited=%t answer=%q", stage, input, missing, result.CoverageLimited, result.Answer.Text)
				}
				for _, label := range missing {
					if !strings.Contains(gap, label) {
						t.Fatalf("%s input=%x did not disclose missing agent %s: %q", stage, input, label, gap)
					}
				}
			}
			for _, item := range originals {
				if _, ok := wanted[item.id]; !ok && strings.Contains(result.Answer.Text, item.fact) {
					t.Fatalf("%s input=%x answered with unavailable agent fact %s", stage, input, item.subject)
				}
			}
			for _, fact := range rejectedFacts {
				if strings.Contains(result.Answer.Text, fact) {
					t.Fatalf("%s input=%x answered a prefix lookalike's fact", stage, input)
				}
			}
		}
		check("before-boundary")
		reopen := func() { closeStore(); open(durable.OpenExisting) }
		if reopenBeforeDelete {
			reopen()
		}
		if deleteAtBoundary {
			item := &originals[unavailable]
			if err := store.DeleteObservationRecord(ctx, item.id); err != nil {
				t.Fatal(err)
			}
			item.live = false
		}
		if !reopenBeforeDelete {
			reopen()
		}
		check("after-boundary")
	})
}

type multiAgentJourneyInput struct {
	data   []byte
	offset int
}

func (d *multiAgentJourneyInput) next() byte {
	if d.offset >= len(d.data) {
		return 0
	}
	b := d.data[d.offset]
	d.offset++
	return b
}

func multiAgentTerminalBody(fact string, size, placement byte) string {
	sizes := [...]int{0, 64, 512, 2048, 4096, 8 << 10}
	length := max(len(fact)+2, sizes[int(size)%len(sizes)])
	n := length - len(fact) - 2
	const line = "Neutral process output.\n"
	filler := strings.Repeat(line, (n+len(line)-1)/len(line))[:n]
	switch placement % 3 {
	case 0:
		return fact + "\n" + filler + "\n"
	case 1:
		return filler + "\n" + fact + "\n"
	default:
		middle := len(filler) / 2
		return filler[:middle] + "\n" + fact + "\n" + filler[middle:]
	}
}
