package darwin

import (
	"errors"
	"net/url"

	"github.com/golang-gui/goui/platform/darwin/frameworks/appkit"
	"github.com/golang-gui/goui/platform/darwin/frameworks/foundation"
)

var errAccountBrowserUnavailable = errors.New("darwin: account browser unavailable")

func validChatGPTAuthorizationURL(raw string) bool {
	u, err := url.Parse(raw)
	return err == nil && len(raw) <= 8192 && u.Scheme == "https" && u.Host == "auth.openai.com" && u.Path == "/api/accounts/authorize" && u.RawPath == "" && u.User == nil && u.Fragment == "" && u.Opaque == ""
}

// OpenChatGPTAuthorization is called only by an explicit sign-in action, on
// the UI thread. The callback URL is generated by Blur's OAuth transaction.
func OpenChatGPTAuthorization(raw string) error {
	if !validChatGPTAuthorizationURL(raw) {
		return errAccountBrowserUnavailable
	}
	return openAccountBrowserURL(raw)
}
func OpenChatGPTUsage() error { return openAccountBrowserURL("https://chatgpt.com/settings/usage") }
func openAccountBrowserURL(raw string) error {
	workspace := appkit.NSWorkspaceClassId.SharedWorkspace()
	if workspace.ID == 0 {
		return errAccountBrowserUnavailable
	}
	value := foundation.ToNSString(raw)
	defer releaseNativeObject(value.ID)
	u := appkit.NSURLClassId.URLWithString(value)
	if u.ID == 0 || !workspace.OpenURL(u) {
		return errAccountBrowserUnavailable
	}
	return nil
}
